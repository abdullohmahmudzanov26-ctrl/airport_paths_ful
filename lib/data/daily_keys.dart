/// Утилита дневных ключей: превращает дату в целое число вида
/// 20260815, которым помечается любой «раз в сутки» прогресс -
/// дневной лимит рекламы, дневной бонус монет, ежедневное пополнение
/// подсказок.
///
/// Раньше здесь же жила механика «Рейс дня» (отдельный ежедневный
/// уровень со своей серией и наградой) - она убрана из игры целиком.
/// Остальные функции, которые просто сверяются с «какой сегодня день»,
/// её не касались и продолжают работать как прежде.
class DailyKeys {
  const DailyKeys._();

  /// Дата в виде 20260815.
  static int keyFor(DateTime date) =>
      date.year * 10000 + date.month * 100 + date.day;

  static int todayKey() => keyFor(DateTime.now());

  static int yesterdayKey() =>
      keyFor(DateTime.now().subtract(const Duration(days: 1)));
}
