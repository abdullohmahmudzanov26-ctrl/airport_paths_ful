  static const List<String> supported = <String>['en', 'es'];

  static String _language = fallback;

  static String get language => _language;

  static set language(String code) {
    _language = supported.contains(code) ? code : fallback;
  }

  /// Язык устройства, если он поддерживается. Иначе английский.
  static String resolveDeviceLanguage(String deviceCode) {
    final String code =
        deviceCode.toLowerCase().split('_').first.split('-').first;
    return supported.contains(code) ? code : fallback;
  }

  static String t(String key) {
    if (_language == 'es') {
      return _es[key] ?? _en[key] ?? key;
    }
    return _en[key] ?? key;
  }

