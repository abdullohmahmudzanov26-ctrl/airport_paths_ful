/// Единственное место, где включаются платные и отладочные системы.
///
/// Зачем отдельный файл: перед сборкой релиза нужно проверить ровно
/// один экран кода, а не искать заглушки по всему проекту. Каждый флаг
/// здесь выключает целую подсистему целиком и безопасно - выключенная
/// система не выдаёт награду, а честно сообщает, что недоступна.
class AppConfig {
  const AppConfig._();

  /// Версия для футера меню и экрана «Об игре». Держать в одном месте,
  /// чтобы она не разъезжалась с pubspec.yaml.
  static const String version = '1.0.0';

  /// Покупки за реальные деньги.
  ///
  /// ВАЖНО перед публикацией: пока в PurchaseService стоит заглушка
  /// (_processPayment не обращается ни к какому стору), этот флаг
  /// ОБЯЗАН оставаться false. Иначе игра раздаёт платные товары
  /// бесплатно, а App Store отклоняет приложение, в котором кнопка
  /// с ценой ничего не покупает (Guideline 2.1 / 3.1.1).
  ///
  /// Ставить true можно только после того, как подключён in_app_purchase
  /// и товары с теми же id заведены в App Store Connect.
  static const bool iapEnabled = false;

  /// Реклама с наградой.
  ///
  /// Та же логика: пока AdService._present() - заглушка, флаг false,
  /// и кнопка «посмотреть ролик» не показывается вообще. Игрок не
  /// упирается в тупик: вместо ролика ему предлагают купить подсказки
  /// за внутриигровые монеты, которые в игре реально зарабатываются.
  static const bool adsEnabled = false;

  /// Набор подсказок за внутриигровые монеты - тот самый, что продаётся
  /// на вкладке EXTRAS в магазине. Вынесен сюда, потому что теперь его
  /// предлагает ещё и игровой экран, когда подсказки кончились: это
  /// рабочий выход из тупика, который не зависит ни от рекламы, ни от
  /// стора. Значения должны совпадать с ShopScreen.hintPackSize/Price.
  static const int hintPackSize = 3;
  static const int hintPackPrice = 150;

  /// Отладочная разблокировка всех уровней. В релизе ВСЕГДА false:
  /// с true игрок сразу видит 200 открытых уровней, и вся кампания,
  /// награды за прохождение и обучение теряют смысл.
  static const bool unlockAllLevels = false;
}
